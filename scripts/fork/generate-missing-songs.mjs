// Fork-only (Admirable0531/mai-tools). Run daily by .github/workflows/sync-upstream.yml.
//
// Writes public/data/fork/missing-songs-auto.json: every chart that
// zetaraku's arcade-songs data has but upstream's song lists ("magic") don't
// yet. Upstream can lag a new chart by weeks, and the rating calculator
// leaves a chart it doesn't know out of the rating; arcade-songs had
// OV3RCLOCK with its constant days earlier. At runtime these only fill gaps
// (see src/common/infra/fork-missing-songs.ts), so once upstream adds a song
// its own data is used, and the song drops out of this file on the next run.
//
// Usage: node scripts/fork/generate-missing-songs.mjs
import {readFileSync, writeFileSync} from 'node:fs';

const ARCADE_SONGS_URL = 'https://dp4p6x0xfi5o9.cloudfront.net/maimai/data.json';
const OUTPUT = 'public/data/fork/missing-songs-auto.json';
const DIFFICULTIES = ['basic', 'advanced', 'expert', 'master', 'remaster'];

async function fetchJson(url) {
  const res = await fetch(url, {signal: AbortSignal.timeout(60000)});
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

/** Version names in index order, read from the source so they can't drift. */
function readVersionNames() {
  const src = readFileSync('src/common/game-version.ts', 'utf8');
  const body = src.match(/const VERSION_NAMES = \[([\s\S]*?)\];/)[1];
  return [...body.matchAll(/^\s*'([^']+)'/gm)].map((m) => m[1]);
}

/** Upstream's song list URLs, decoded from magic-api.ts, keyed by version enum name. */
function readMagicUrls() {
  const src = readFileSync('src/common/infra/magic-api.ts', 'utf8');
  return [...src.matchAll(/GameVersion\.(\w+),\s*'([A-Za-z0-9+/=]+)'/g)].map(([, ver, b64]) => ({
    ver,
    url: Buffer.from(b64, 'base64').toString('utf8'),
  }));
}

const versionNames = readVersionNames();
const versionIndex = (name) =>
  versionNames.indexOf(name.replace(/^maimaiでらっくす/, 'でらっくす'));

// The two newest lists: the current International version and the newest
// Japanese one. A chart missing from the newest list, or available in
// International but missing from that version's list, is a gap.
const magicUrls = readMagicUrls().slice(-2);
const magics = await Promise.all(magicUrls.map(({url}) => fetchJson(url)));
const known = magics.map((songs) => new Set(songs.map((s) => `${s.dx}\t${s.name}`)));
const [intlKnown, newestKnown] = known;

const data = await fetchJson(ARCADE_SONGS_URL);
const output = [];
for (const song of data.songs) {
  if (song.category === '宴会場') continue;
  for (const [type, dx] of [['std', 0], ['dx', 1]]) {
    const sheets = song.sheets.filter((sh) => sh.type === type && !/\?/.test(sh.level));
    if (sheets.length === 0) continue;
    const key = `${dx}\t${song.title}`;
    const onIntl = sheets.some((sh) => sh.regions?.intl);
    if (newestKnown.has(key) && !(onIntl && !intlKnown.has(key))) continue;

    const lv = DIFFICULTIES.map((difficulty) => {
      const sheet = sheets.find((sh) => sh.difficulty === difficulty);
      if (!sheet) return null;
      // Positive = exact constant; negative = only the official level is
      // known (arcade-songs' levelValue is that level's minimum, 12+ -> 12.6).
      return sheet.internalLevel != null ? sheet.internalLevelValue : -sheet.levelValue;
    });
    if (lv.slice(0, 4).some((v) => v == null)) continue;
    if (lv[4] == null) lv.pop();

    const debut = versionIndex(song.version);
    if (debut < 0) {
      console.warn(`Skipping ${song.title} (${type}): unknown version "${song.version}"`);
      continue;
    }
    const intlVersion = sheets.find((sh) => sh.regionOverrides?.intl?.version)?.regionOverrides
      .intl.version;
    const intlDebut = intlVersion ? versionIndex(intlVersion) : -1;

    output.push({
      name: song.title,
      genre: song.category,
      dx,
      debut,
      lv,
      ...(intlDebut >= 0 && intlDebut !== debut ? {regionOverrides: {intl: {debut: intlDebut}}} : {}),
    });
  }
}
output.sort((a, b) => a.name.localeCompare(b.name) || a.dx - b.dx);

// No timestamp, so the file (and the repo) only changes when the gaps do.
const json =
  JSON.stringify(
    {
      _comment:
        'Generated by scripts/fork/generate-missing-songs.mjs from arcade-songs (zetaraku) — do not edit; ' +
        'put hand-made entries in missing-songs.json, which takes precedence.',
      comparedAgainst: magicUrls.map(({ver}) => ver),
      songs: output,
    },
    null,
    2,
  ) + '\n';
writeFileSync(OUTPUT, json);
console.log(`${output.length} chart(s) missing from upstream: ${output.map((s) => s.name).join(', ')}`);
